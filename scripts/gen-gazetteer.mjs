/**
 * Emits public/gazetteer.json from src/lib/desk/gazetteer.ts.
 *
 * The browser bundle is a plain script with no build step, so it cannot import
 * the TypeScript module. Rather than keep two hand-maintained copies of the place
 * table, the server module stays the single source of truth and this script
 * projects it into JSON.
 *
 *   node --experimental-strip-types scripts/gen-gazetteer.mjs
 */

import { writeFile } from "node:fs/promises";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

import { PLACES, shortWhere } from "../src/lib/desk/gazetteer.ts";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "public", "gazetteer.json");

const payload = {
  note: "Generated by scripts/gen-gazetteer.mjs from src/lib/desk/gazetteer.ts — do not edit by hand.",
  generatedAt: new Date().toISOString(),
  places: PLACES.map((p) => ({
    name: p.name,
    lat: p.lat,
    lng: p.lng,
    kind: p.kind,
    country: p.country,
    ...(p.region ? { region: p.region } : {}),
    // The card-length locator, resolved here so the browser never has to
    // re-derive it and drift from the server's wording.
    ...(shortWhere(p) ? { where: shortWhere(p) } : {}),
    ...(p.wellKnown ? { wellKnown: true } : {}),
    ...(p.dateline ? { dateline: p.dateline } : {}),
    aliases: p.aliases,
  })),
};

await writeFile(out, JSON.stringify(payload, null, 2), "utf8");
console.log(`gazetteer.json: ${payload.places.length} places → ${out}`);
