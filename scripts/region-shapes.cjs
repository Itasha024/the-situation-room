/**
 * Builds src/lib/desk/region-shapes.ts: light outlines of the countries the
 * main desk tags reports by (option C). Inputs are the map files already in
 * public/ (Natural Earth via iran-countries, geoBoundaries Yemen ADM1), cut to
 * two decimals (about 1 km). Gaza and Judea and Samaria are drawn by hand,
 * coarse, inside Israel's outline, and are tested before it.
 *   node scripts/region-shapes.cjs
 */
const fs = require("fs");
const P = (p) => JSON.parse(fs.readFileSync(p, "utf8"));
const r2 = (v) => Math.round(v * 100) / 100;
function ring(rg, step) {
  const o = [];
  let last = null;
  for (const [x, y] of rg) {
    const q = [r2(x), r2(y)];
    if (!last || Math.abs(q[0] - last[0]) + Math.abs(q[1] - last[1]) >= step) { o.push(q); last = q; }
  }
  return o.length > 3 ? o : null;
}
const polys = (g, step) => (g.type === "Polygon" ? [g.coordinates] : g.coordinates).map((p) => p.map((x) => ring(x, step)).filter(Boolean)).filter((p) => p.length);
const ID = { "United Arab Emirates": "gulf", Qatar: "gulf", Bahrain: "gulf", Kuwait: "gulf", Oman: "gulf", "Saudi Arabia": "saudi", Lebanon: "lebanon", "Israel, Judea and Samaria": "israel", Iraq: "iraq", Iran: "iran", Syria: "syria", Jordan: "jordan", Turkey: "turkey", Egypt: "egypt", Cyprus: "cyprus", "N. Cyprus": "cyprus", Azerbaijan: "azerbaijan" };
const shapes = [];
shapes.push({ id: "gaza", polys: [[[[34.22, 31.32], [34.27, 31.22], [34.37, 31.29], [34.56, 31.54], [34.49, 31.6], [34.22, 31.32]]]] });
shapes.push({ id: "judea-samaria", polys: [[[[35.0, 31.35], [34.88, 31.4], [34.95, 31.9], [35.0, 32.15], [34.95, 32.4], [35.08, 32.55], [35.4, 32.52], [35.57, 32.4], [35.55, 31.75], [35.48, 31.45], [35.3, 31.35], [35.0, 31.35]]]] });
shapes.push({ id: "yemen", polys: P("public/yemen-adm1.geojson").features.flatMap((f) => polys(f.geometry, 0.03)) });
for (const f of P("public/iran-countries.geojson").features) shapes.push({ id: ID[f.properties.name] || "other", polys: polys(f.geometry, 0.03) });
const out = `/* Generated by scripts/region-shapes.cjs — do not edit by hand. */\nexport type Shape = { id: string; polys: number[][][][] };\nexport const SHAPES: Shape[] = ${JSON.stringify(shapes)};\n`;
fs.writeFileSync("src/lib/desk/region-shapes.ts", out);
console.log("region-shapes.ts", (out.length / 1024).toFixed(0) + " KB", shapes.length, "shapes");
